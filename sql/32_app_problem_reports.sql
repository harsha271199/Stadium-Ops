-- fix-177: "Report an app problem" from the home screen.
-- Anyone signed in can ADD a report; nobody can read them with the public key (Admin reads in Supabase).
create table if not exists public.app_problem_reports (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  employee_id text default '', name text default '', role text default '', stand text default '',
  kind text default '', note text not null check (char_length(note) between 1 and 1000),
  screen text default '', build_tag text default '', user_agent text default '',
  status text not null default 'new'
);
alter table public.app_problem_reports enable row level security;
drop policy if exists app_problem_reports_insert on public.app_problem_reports;
create policy app_problem_reports_insert on public.app_problem_reports for insert to anon with check (true);
revoke all on public.app_problem_reports from anon;
grant insert on public.app_problem_reports to anon;
